extension RandomGenerators {
    /// A generator that selects from multiple generators with different frequencies.
    ///
    /// The `Frequency` generator allows you to create weighted random selections by specifying
    /// how frequently each generator should be chosen. Generators with higher frequency values
    /// will be selected more often than those with lower values.
    ///
    /// Example usage:
    /// ```swift
    /// // A weighted die: 1-3 comes up three times as often as 4-6
    /// let low = IntGenerator(in: 1...3)
    /// let high = IntGenerator(in: 4...6)
    ///
    /// let weightedDice = RandomGenerators.frequency([
    ///     (3, low),   // 3x weight
    ///     (1, high)   // 1x weight
    /// ])
    ///
    /// // Roll the weighted dice - 75% chance of low, 25% chance of high
    /// let roll = weightedDice.run()
    /// ```
    ///
    /// To mix generators of different concrete types, erase them first:
    /// ```swift
    /// let mixed = RandomGenerators.frequency([
    ///     (2, IntGenerator(in: 1...6).eraseToAnyRandomGenerator()),
    ///     (1, Always(0).eraseToAnyRandomGenerator())
    /// ])
    /// ```
    public struct Frequency<Upstream: RandomGenerator>: RandomGenerator {
        /// The type of elements produced by this generator.
        public typealias Element = Upstream.Element

        /// Each generator paired with the upper bound of its cumulative weight range,
        /// so a single integer draw selects a generator via binary search.
        private let cumulative: [(bound: Int, generator: Upstream)]

        /// The sum of all weights in the distribution.
        private let totalWeight: Int

        /// Initializes a new frequency generator with the given distribution.
        ///
        /// Entries with zero weight are never selected and are dropped up front.
        ///
        /// - Parameter distribution: An array of tuples where each tuple contains a frequency (weight)
        ///   and a generator. Generators with higher frequency values will be selected more often.
        /// - Precondition: The distribution must contain at least one entry with a positive
        ///   weight, and no weight may be negative.
        public init(_ distribution: [(Int, Upstream)]) {
            precondition(!distribution.isEmpty, "Frequency requires a non-empty distribution")
            var running = 0
            var cumulative: [(bound: Int, generator: Upstream)] = []
            cumulative.reserveCapacity(distribution.count)
            for (weight, generator) in distribution {
                precondition(weight >= 0, "Frequency weights must be non-negative, got \(weight)")
                guard weight > 0 else { continue }
                running += weight
                cumulative.append((bound: running, generator: generator))
            }
            precondition(running > 0, "Frequency requires at least one positive weight")
            self.cumulative = cumulative
            self.totalWeight = running
        }

        /// Runs the generator using the provided random number generator.
        /// - Parameter rng: The random number generator to use.
        /// - Returns: A value generated by one of the upstream generators, selected according to the frequency distribution.
        public func run<RNG: RandomNumberGenerator>(using rng: inout RNG) -> Upstream.Element {
            let draw = IntGenerator(in: 1...totalWeight).run(using: &rng)
            // Binary search for the first cumulative bound >= draw.
            var low = 0
            var high = cumulative.count - 1
            while low < high {
                let mid = (low + high) / 2
                if cumulative[mid].bound < draw {
                    low = mid + 1
                } else {
                    high = mid
                }
            }
            return cumulative[low].generator.run(using: &rng)
        }
    }
}

public extension RandomGenerators {
    /// Creates a generator that selects from multiple generators with different frequencies.
    ///
    /// The frequency values determine the relative probability of each generator being
    /// selected. Entries with zero weight are never selected.
    ///
    /// - Parameter distribution: An array of tuples where each tuple contains a frequency (weight)
    ///   and a generator. Generators with higher frequency values will be selected more often.
    /// - Returns: A generator that produces values from the weighted selection of generators.
    /// - Precondition: The distribution must contain at least one entry with a positive
    ///   weight, and no weight may be negative.
    static func frequency<G: RandomGenerator>(_ distribution: [(Int, G)]) -> Frequency<G> {
        Frequency(distribution)
    }
}
